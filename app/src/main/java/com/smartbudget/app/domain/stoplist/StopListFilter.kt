data class UserFoodPreferences(
    val excludedCategories: Set<FoodCategory> = emptySet(),
    val customStopWords: Set<String> = emptySet()
) {
    /**
     * Возвращает полный список слов для поиска и исключения в нижнем регистре.
     */
    fun getAllStopWords(): Set<String> {
        val fromCategories = excludedCategories.flatMap { it.defaultKeywords }
        return (fromCategories + customStopWords).map { it.trim().lowercase() }.filter { it.isNotBlank() }.toSet()
    }
}

object StopListFilter {

    /**
     * Проверяет, разрешен ли продукт/рецепт пользователю с учетом стоп-листа.
     */
    fun isAllowed(
        title: String,
        description: String = "",
        composition: String = "",
        preferences: UserFoodPreferences
    ): Boolean {
        val stopWords = preferences.getAllStopWords()
        if (stopWords.isEmpty()) return true

        val fullText = "$title $description $composition".lowercase()

        for (word in stopWords) {
            if (fullText.contains(word)) {
                return false
            }
        }
        return true
    }
}
